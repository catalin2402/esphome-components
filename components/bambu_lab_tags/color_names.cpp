const char *get_color_name(const std::string &material_id, const std::string &variant_id) {
  // A00-W1 belongs to GFA00; do not label mismatched material/variant pairs.
  if (material_id.size() != 5 || material_id.compare(0, 2, "GF") != 0 || variant_id.size() < 5 ||
      variant_id.compare(0, 3, material_id, 2, 3) != 0 || variant_id[3] != '-')
    return nullptr;
  const auto *entry = std::lower_bound(std::begin(COLOR_NAMES), std::end(COLOR_NAMES), variant_id,
                                       [](const ColorName &entry, const std::string &value) {
                                         return std::strcmp(entry.variant_id, value.c_str()) < 0;
                                       });
  if (entry == std::end(COLOR_NAMES) || variant_id != entry->variant_id)
    return nullptr;
  return entry->name;
}

